// ── dbMock plumbing ─────────────────────────────────────────────────
const dbHolder: { current: DeepMockProxy<PrismaClient> | null } = {
  current: null,
};
function getDbMock(): DeepMockProxy<PrismaClient> {
  if (!dbHolder.current) {
    dbHolder.current = mockDeep<PrismaClient>();
  }
  return dbHolder.current;
}

vi.mock("~/server/db", () => {
  const proxy = new Proxy(
    {},
    {
      get(_t, prop) {
        const m = getDbMock() as unknown as Record<string | symbol, unknown>;
        return m[prop as string];
      },
    },
  );
  return { db: proxy };
});


import { createCaller } from "~/server/api/root";
import { createMockCaller } from "~/test/trpc-helpers";

describe("goal.myPublicGoals", () => {
  let dbMock: DeepMockProxy<PrismaClient>;

  beforeEach(() => {
    dbMock = getDbMock();
    mockReset(dbMock);
    dbMock.goal.findMany.mockResolvedValue([]);
  });

  it("refuses anonymous callers without querying", async () => {
    const anonymous = createCaller({
      db: dbMock,
      session: null,
      headers: new Headers(),
    });

    await expect(anonymous.goal.myPublicGoals()).rejects.toMatchObject({
      code: "UNAUTHORIZED",
    });
    expect(dbMock.goal.findMany).not.toHaveBeenCalled();
  });

  it("returns only the signed-in caller's goals", async () => {
    const caller = createMockCaller({ userId: "user-1", db: dbMock });

    await caller.goal.myPublicGoals();

    expect(dbMock.goal.findMany).toHaveBeenCalledWith(
      expect.objectContaining({ where: { userId: "user-1" } }),
    );
  });
});
