/**
 * Builds the agent procedure contract: the input of every procedure an agent
 * tool calls, as JSON Schema. The Mastra repo keeps a copy and checks each
 * tool's request against it, so a tool cannot drift from the procedure it
 * calls without a test failing.
 */
import type { ZodTypeAny } from "zod";

import { zodInputToJsonSchema, type JsonSchema } from "./zodInputToJsonSchema";

export const CONTRACT_VERSION = 1;

export interface ProcedureContract {
  /** Agent tools POST to queries and mutations alike (ADR-0041). A GET only reaches a query. */
  type: "query" | "mutation";
  /** True when the procedure accepts a call with no input at all. */
  inputOptional: boolean;
  /** JSON Schema (draft-07) of the input. `null` when the procedure declares none. */
  input: JsonSchema | null;
}

export interface AgentProcedureContract {
  $comment: string;
  version: number;
  jsonSchemaDialect: string;
  procedures: Record<string, ProcedureContract>;
}

/** The part of a tRPC procedure this module reads. */
export interface ProcedureLike {
  _def: { type?: string; inputs?: unknown[] };
}

export interface ContractSelection {
  routers: readonly string[];
  procedures: readonly string[];
}

function isZodSchema(value: unknown): value is ZodTypeAny {
  return (
    typeof value === "object" &&
    value !== null &&
    "_def" in value &&
    typeof (value as { safeParse?: unknown }).safeParse === "function"
  );
}

function acceptsNoInput(schemas: ZodTypeAny[]): boolean {
  try {
    return schemas.every((schema) => schema.safeParse(undefined).success);
  } catch {
    // An async refinement throws from safeParse. Treat the input as required.
    return false;
  }
}

function describeProcedure(path: string, procedure: ProcedureLike): ProcedureContract {
  const type = procedure._def.type;
  if (type !== "query" && type !== "mutation") {
    throw new Error(
      `${path} is a ${String(type)}. The agent procedure contract covers queries and mutations only.`,
    );
  }

  const inputs = procedure._def.inputs ?? [];
  if (inputs.length === 0) {
    return { type, inputOptional: true, input: null };
  }

  const schemas = inputs.map((input) => {
    if (!isZodSchema(input)) {
      throw new Error(`${path} has an input that is not a zod schema. The contract cannot describe it.`);
    }
    return input;
  });
  const converted = schemas.map(zodInputToJsonSchema);

  return {
    type,
    inputOptional: acceptsNoInput(schemas),
    // tRPC parses each `.input()` in turn, so a payload must satisfy all of them.
    input: converted.length === 1 ? converted[0]! : { allOf: converted },
  };
}

export function buildAgentProcedureContract(
  allProcedures: Record<string, ProcedureLike>,
  selection: ContractSelection,
): AgentProcedureContract {
  const paths = new Set<string>();

  for (const router of selection.routers) {
    const prefix = `${router}.`;
    const found = Object.keys(allProcedures).filter((path) => path.startsWith(prefix));
    if (found.length === 0) {
      throw new Error(`Router "${router}" has no procedures. Remove it from AGENT_ROUTERS or fix the name.`);
    }
    for (const path of found) paths.add(path);
  }

  for (const path of selection.procedures) {
    if (!(path in allProcedures)) {
      throw new Error(
        `Procedure "${path}" does not exist. An agent tool calls it: restore it, or change the tool and remove the path from AGENT_PROCEDURES.`,
      );
    }
    paths.add(path);
  }

  const procedures: Record<string, ProcedureContract> = {};
  for (const path of [...paths].sort()) {
    procedures[path] = describeProcedure(path, allProcedures[path]!);
  }

  return {
    $comment:
      "Generated by `npm run contracts:generate`. Do not edit by hand. The Mastra repo checks every agent tool's request against this file.",
    version: CONTRACT_VERSION,
    jsonSchemaDialect: "http://json-schema.org/draft-07/schema#",
    procedures,
  };
}

/** The exact bytes of the committed file. */
export function serializeContract(contract: AgentProcedureContract): string {
  return `${JSON.stringify(contract, null, 2)}\n`;
}
